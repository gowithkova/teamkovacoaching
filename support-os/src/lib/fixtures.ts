// Availability: generated across a 21-day window so Today/Calendar always
// show a live, non-stale pattern rather than fixed calendar dates.
function generateAvailabilityBlocks(): AvailabilityBlock[] {
  const blocks: AvailabilityBlock[] = [];
  for (let offset = -7; offset <= 21; offset++) {
    const dow = weekdayForOffset(offset);
    if (dow >= 1 && dow <= 5) {
      blocks.push({
        id: `ab-school-${offset}`,
        startAt: brisbaneDayOffset(offset, 15, 0),
        endAt: brisbaneDayOffset(offset, 16, 30),
        blockType: "parenting",
        displayLabel: "School pickup",
        recurring: true,
      });
    }
    if (dow === 2 || dow === 4) {
      blocks.push({
        id: `ab-kitchen-${offset}`,
        startAt: brisbaneDayOffset(offset, 17, 30),
        endAt: brisbaneDayOffset(offset, 22, 0),
        blockType: "other_employment",
        displayLabel: "Kitchen shift — The Point",
        recurring: true,
      });
    }
    if (dow === 6) {
      blocks.push({
        id: `ab-saturday-${offset}`,
        startAt: brisbaneDayOffset(offset, 0, 0),
        endAt: brisbaneDayOffset(offset, 23, 59),
        blockType: "unavailable",
        displayLabel: "Family day — unavailable",
        recurring: true,
      });
    }
    if (dow === 0) {
      blocks.push({
        id: `ab-sunday-am-${offset}`,
        startAt: brisbaneDayOffset(offset, 7, 0),
        endAt: brisbaneDayOffset(offset, 8, 30),
        blockType: "personal",
        displayLabel: "Training / admin",
        recurring: true,
      });
    }
  }
  return blocks;
}

